"""Read-only reconstruction of the paper's memory-ten finite contract.

Only the supplied Lean data file is read. No archived executable or data file
is used; raw words are generated by extending paths along unused bonds.
"""

from collections import Counter
import hashlib
import json
from pathlib import Path
import re


ROOT = Path('/home/ubuntu/aklt/reports/FID_T048')
SOURCE = Path('/home/ubuntu/aklt/review/FID_T/lean/AKLT/Defs/Automaton10Data.lean')
source = SOURCE.read_text()
literals = {}
literal_lines = {}
expressions = {}
for line_number, line in enumerate(source.splitlines(), 1):
    match = re.fullmatch(r'private noncomputable def (\w+) : ℕ := 0x([0-9a-f]+)', line)
    if match:
        name, digits = match.groups()
        literals[name] = int(digits, 16)
        literal_lines[name] = line_number
    match = re.fullmatch(r'noncomputable def (\w+) : ℕ := (.*)', line)
    if match:
        expressions[match[1]] = match[2]


def parse_expression(expression):
    """Evaluate + and <<< and independently retain every literal's bit offset."""
    tokens = re.findall(r'\w+|<<<|[()+]', expression)
    assert ''.join(tokens) == re.sub(r'\s+', '', expression)
    cursor = 0

    def atom():
        nonlocal cursor
        token = tokens[cursor]
        cursor += 1
        if token == '(':
            value, placements = addition()
            assert tokens[cursor] == ')'
            cursor += 1
            return value, placements
        assert token in literals
        return literals[token], {token: 0}

    def shift():
        nonlocal cursor
        value, placements = atom()
        while cursor < len(tokens) and tokens[cursor] == '<<<':
            cursor += 1
            bits = int(tokens[cursor])
            cursor += 1
            value <<= bits
            placements = {name: offset + bits for name, offset in placements.items()}
        return value, placements

    def addition():
        nonlocal cursor
        value, placements = shift()
        while cursor < len(tokens) and tokens[cursor] == '+':
            cursor += 1
            right, other_placements = shift()
            assert not placements.keys() & other_placements.keys()
            value += right
            placements.update(other_placements)
        return value, placements

    value, placements = addition()
    assert cursor == len(tokens)
    # Check disjoint bit intervals: addition cannot introduce a carry.
    intervals = sorted((offset, offset + literals[name].bit_length(), name)
                       for name, offset in placements.items())
    assert all(left[1] <= right[0] for left, right in zip(intervals, intervals[1:]))
    assert value == sum(literals[name] << offset for name, offset in placements.items())
    return value, placements


tables = {}
placements = {}
for name, expression in expressions.items():
    value, offsets = parse_expression(expression)
    tables[name] = value.to_bytes((value.bit_length() + 7) // 8, 'little')
    placements[name] = offsets


def lane(name, width, index):
    start = width * index
    byte_index, bit_index = divmod(start, 8)
    end = byte_index + (bit_index + width + 7) // 8
    return (int.from_bytes(tables[name][byte_index:end], 'little') >> bit_index) % (1 << width)


classes = [lane('rawClass', 12, code) for code in range(4 ** 10)]
representatives = [lane('representatives', 20, a) for a in range(3741)]
destinations = [[lane('destinations', 12, a * 4 + d) for d in range(4)] for a in range(3741)]
kinds = [[lane('edgeKinds', 2, a * 4 + d) for d in range(4)] for a in range(3741)]

STEPS = ((1, 0), (0, 1), (-1, 0), (0, -1))


def bond(x, y):
    return tuple(sorted((x, y)))


def raw_info(code):
    word = tuple((code >> (2 * (9 - i))) % 4 for i in range(10))
    vertices = [(0, 0)]
    bonds = []
    for direction in word:
        dx, dy = STEPS[direction]
        x, y = vertices[-1]
        new = (x + dx, y + dy)
        bonds.append(bond((x, y), new))
        vertices.append(new)
    is_raw = len(set(bonds)) == 10
    revisit = vertices[-1] in vertices[:-1]
    arrival = word[-1]
    admissible = []
    raw_kinds = []
    endpoint = vertices[-1]
    for direction, (dx, dy) in enumerate(STEPS):
        new = (endpoint[0] + dx, endpoint[1] + dy)
        admissible.append(direction != (arrival + 2) % 4 and bond(endpoint, new) not in bonds)
        raw_kinds.append(2 if revisit else 0 if direction == arrival else 1)
    return is_raw, arrival, admissible, raw_kinds


raw_codes = []
depth_counts = [0] * 11


def generate(depth=0, code=0, endpoint=(0, 0), used=None):
    if used is None:
        used = set()
    depth_counts[depth] += 1
    if depth == 10:
        raw_codes.append(code)
        return
    for direction, (dx, dy) in enumerate(STEPS):
        new = (endpoint[0] + dx, endpoint[1] + dy)
        edge = bond(endpoint, new)
        if edge not in used:
            used.add(edge)
            generate(depth + 1, code * 4 + direction, new, used)
            used.remove(edge)


generate()
assert raw_codes == sorted(set(raw_codes))
raw_set = set(raw_codes)
errors = Counter()
examples = {}


def require(condition, category, detail):
    if not condition:
        errors[category] += 1
        examples.setdefault(category, detail)


for code, a in enumerate(classes):
    require(a <= 3741, 'class_bounds', [code, a])
    require((a < 3741) == (code in raw_set), 'raw_coverage', [code, a])

representative_info = []
for a, code in enumerate(representatives):
    require(code < 4 ** 10, 'representative_bounds', [a, code])
    info = raw_info(code)
    representative_info.append(info)
    require(info[0] and code in raw_set, 'representative_raw', [a, code])
    require(classes[code] == a, 'representative_class', [a, code, classes[code]])
    for d in range(4):
        dest = destinations[a][d]
        kind = kinds[a][d]
        require(dest <= 3741, 'destination_bounds', [a, d, dest])
        require((dest == 0) == (kind == 3), 'inadmissible_sentinel', [a, d, dest, kind])
        require(dest == 0 or kind < 3, 'kind_bounds', [a, d, kind])

for code in raw_codes:
    a = classes[code]
    if a >= 3741:
        continue
    raw, arrival, admissible, raw_kinds = raw_info(code)
    require(raw, 'generated_raw', code)
    _, rep_arrival, rep_admissible, rep_kinds = representative_info[a]
    for d in range(4):
        require(admissible[d] == rep_admissible[d], 'class_admissibility', [code, a, d])
        # The paper's lemma asks for identical kind for every absolute direction.
        require(raw_kinds[d] == rep_kinds[d], 'class_kind_all_directions', [code, a, d])
        require(admissible[d] == (destinations[a][d] != 0), 'stored_admissibility', [code, a, d])
        if admissible[d]:
            successor = (code % (4 ** 9)) * 4 + d
            require(successor in raw_set, 'successor_raw', [code, d, successor])
            require(destinations[a][d] == classes[successor] + 1, 'stored_successor',
                    [code, a, d, destinations[a][d], classes[successor]])
            require(raw_kinds[d] == kinds[a][d], 'stored_kind', [code, a, d])
            require(raw_kinds[d] == 2 or arrival == rep_arrival, 'nonrevisit_arrival', [code, a, d])

edge_counts = Counter(kinds[a][d] for a in range(3741) for d in range(4) if destinations[a][d])
require(depth_counts[1:] == [4, 12, 36, 108, 316, 916, 2628, 7500, 21268, 60092],
        'paper_depth_counts', depth_counts)
require(edge_counts == Counter({0: 2516, 1: 5032, 2: 1872}), 'paper_edge_counts', dict(edge_counts))

chunks = []
for index in range(205, 210):
    name = f'rawClass_{index}'
    start = placements['rawClass'][name]
    # All these chunks occupy a full 16384-bit slot, including leading zeros.
    end = start + 16384
    first_code = start // 12
    last_code = (end - 1) // 12
    affected = range(first_code, last_code + 1)
    valid = [code for code in affected if code in raw_set]
    lane_values = Counter(classes[code] for code in affected)
    boundary_lanes = []
    for code in (first_code, last_code):
        overlap_start = max(start, code * 12)
        overlap_end = min(end, (code + 1) * 12)
        boundary_lanes.append({'code': code, 'value': classes[code],
                               'lane_bit_start': overlap_start - code * 12,
                               'lane_bit_end_exclusive': overlap_end - code * 12})
    chunks.append({
        'declaration': name,
        'lean_line': literal_lines[name],
        'bit_start': start,
        'bit_end_exclusive': end,
        'first_code': first_code,
        'last_code': last_code,
        'touched_lanes': len(affected),
        'raw_lanes': len(valid),
        'nonraw_lanes': len(affected) - len(valid),
        'distinct_raw_classes': len({classes[code] for code in valid}),
        'raw_class_min': min((classes[code] for code in valid), default=None),
        'raw_class_max': max((classes[code] for code in valid), default=None),
        'boundary_lanes': boundary_lanes,
        'raw_example': {'code': valid[0], 'class': classes[valid[0]],
                        'representative': representatives[classes[valid[0]]]} if valid else None,
        'value_counts': dict(sorted(lane_values.items())),
        'literal_sha256_hex_ascii': hashlib.sha256(format(literals[name], 'x').encode()).hexdigest(),
    })

result = {
    'literal_counts': dict(Counter(re.sub(r'_\d+$', '', name) for name in literals)),
    'depth_counts': depth_counts[1:],
    'raw_windows': len(raw_codes),
    'distinct_raw_classes': len({classes[code] for code in raw_codes}),
    'raw_class_bound': [min(classes[code] for code in raw_codes), max(classes[code] for code in raw_codes)],
    'nonraw_value_counts': dict(Counter(a for code, a in enumerate(classes) if code not in raw_set)),
    'edge_counts': dict(sorted(edge_counts.items())),
    'errors': dict(errors),
    'error_examples': examples,
    'chunks': chunks,
}
(ROOT / 'check_results.json').write_text(json.dumps(result, indent=2) + '\n')
summary = dict(result)
summary['chunks'] = [{key: value for key, value in item.items() if key != 'value_counts'} for item in chunks]
print(json.dumps(summary, indent=2))
assert not errors, f'Reconstruction found errors: {dict(errors)}'
