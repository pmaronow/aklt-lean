def chunks(name,value):
 h=format(value,'x')
 parts=[h[i:i+4096] for i in range(0,len(h),4096)]
 declarations=[f'private noncomputable def {name}_{i} : ℕ := 0x{part}\n' for i,part in enumerate(parts)]
 def balanced(lo,hi):
  if hi-lo==1:return f'{name}_{lo}',len(parts[lo])
  mid=(lo+hi)//2; a,na=balanced(lo,mid); b,nb=balanced(mid,hi)
  return f'(({a} <<< {4*nb}) + {b})',na+nb
