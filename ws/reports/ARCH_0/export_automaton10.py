# Packed lanes are least-significant-lane first; class 3741 marks every absent code.
# Use byte arrays so the exporter does not repeatedly shift a 12-Mbit integer.
def pack(values,width):
 v=bytearray((len(values)*width+7)//8)
 for i,a in enumerate(values):
  assert 0<=a<2**width
  shift=i*width; j=shift//8; offset=shift%8; a <<= offset
  for k in range((width+offset+7)//8):v[j+k]|=(a>>(8*k))&255
 return int.from_bytes(v,'little')
