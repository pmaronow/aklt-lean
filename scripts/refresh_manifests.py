#!/usr/bin/env python3
"""Refresh or check current source hashes without invoking Lean or Lake."""
import argparse
import csv
import gzip
import hashlib
import io
import json
from pathlib import Path
import subprocess

from make_challenge import render
from source_digest import source_digest

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def protected_paths(root):
    tracked = subprocess.check_output(['git', '-C', str(root), 'ls-files', '-z']).decode().split('\0')
    pins = {'lakefile.toml', 'lake-manifest.json', 'lean-toolchain', 'comparator.json',
            'verification/generated-modules.json'}
    names = {n for n in tracked if n and (n.endswith('.lean') or n in pins or
                                         n.startswith('verification/regen-interface/'))}
    for directory in ['AKLT/Cert/H1/tools', 'AKLT/Cert/H3']:
        names.update(str(p.relative_to(root)) for p in (root / directory).glob('*.py'))
    names.update(['AKLT/Cert/H3/inputs.json', 'AKLT/Cert/H3/prefix-reference.json'])
    return sorted(n for n in names if (root / n).is_file())


def read_tsv(path):
    with Path(path).open(newline='') as stream:
        table = csv.DictReader(stream, delimiter='\t')
        return table.fieldnames, list(table)


def tsv_bytes(fields, rows):
    output = io.StringIO()
    table = csv.DictWriter(output, fieldnames=fields, delimiter='\t', lineterminator='\n')
    table.writeheader()
    table.writerows(rows)
    return output.getvalue().encode()


def expected_tables(root):
    result = {}
    for relative, column in [('verification/port/source-manifest.tsv', 'ported_sha256'),
                             ('verification/port/port-list.tsv', 'sha256')]:
        fields, rows = read_tsv(root / relative)
        for row in rows:
            path = root / row['path']
            row[column] = sha(path)
            if column == 'sha256':
                raw = path.read_bytes()
                row['bytes'] = str(len(raw))
                row['lines'] = str(len(raw.decode().splitlines()))
                row['module_header'] = str(raw.startswith(b'module\n'))
        result[relative] = tsv_bytes(fields, rows)
    return result


def check(root):
    root = Path(root).resolve()
    issues = []
    tables = expected_tables(root)
    for name, expected in tables.items():
        if (root / name).read_bytes() != expected:
            issues.append({'file': name, 'message': 'Current source hashes or sizes are stale'})
    inventory = json.loads((root / 'verification/source-inventory.json').read_text())
    expected_names = set(inventory['handwritten'])
    for name in tables:
        _, rows = read_tsv(root / name)
        if {row['path'] for row in rows} != expected_names or len(rows) != len(expected_names):
            issues.append({'file': name, 'message': 'Source path inventory differs or has duplicate rows'})
    baseline_file = root / 'verification/layout/protected-baseline.json.gz'
    baseline = json.loads(gzip.decompress(baseline_file.read_bytes()))
    current = {name: sha(root / name) for name in protected_paths(root)}
    if baseline['files'] != current:
        issues.append({'file': str(baseline_file.relative_to(root)),
                       'message': 'Source, pin, interface, or tool hashes are stale',
                       'paths': sorted(n for n in set(current) | set(baseline['files'])
                                       if current.get(n) != baseline['files'].get(n))})
    digest, _ = source_digest(root)
    if (root / 'verification/source-digest.txt').read_text().strip() != digest:
        issues.append({'file': 'verification/source-digest.txt', 'message': 'Tracked source digest is stale'})
    challenge, sources = render(root)
    for name, expected in [('Challenge.lean', challenge), ('verification/statement-sources.json', sources)]:
        if (root / name).read_bytes() != expected:
            issues.append({'file': name, 'message': 'Statement generation differs byte for byte'})
    return {'passed': not issues, 'source_digest': digest, 'handwritten_files': len(expected_names),
            'protected_files': len(current), 'issues': issues}


def refresh(root):
    root = Path(root).resolve()
    challenge, sources = render(root)
    if (root / 'Challenge.lean').read_bytes() != challenge:
        raise ValueError('Refusing to change Challenge.lean; generated bytes must already agree')
    for relative, data in expected_tables(root).items():
        (root / relative).write_bytes(data)
    baseline = {'baseline': subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip(),
        'scope': 'Current Lean sources, build pins, interfaces, and portable tools. The baseline commit identifies the Lean sources; tool hashes identify the accompanying tool revision.',
        'files': {name: sha(root / name) for name in protected_paths(root)}}
    (root / 'verification/layout/protected-baseline.json.gz').write_bytes(
        gzip.compress((json.dumps(baseline, indent=2) + '\n').encode(), mtime=0))
    (root / 'verification/statement-sources.json').write_bytes(sources)
    digest, _ = source_digest(root)
    (root / 'verification/source-digest.txt').write_text(digest + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, default=ROOT)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument('--check', action='store_true')
    modes.add_argument('--write', action='store_true')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    if args.write:
        refresh(args.project)
    result = check(args.project)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))
    return 0 if result['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
